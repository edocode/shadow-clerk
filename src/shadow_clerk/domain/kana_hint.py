"""聞き間違いの目印（文字起こしに添える「音のかな」）

文字起こしの語の読みが、音として聞こえたかなと食い違うとき、その語の直後に
`(でぷろい?)` の形で音のかなを添える。置き換えはしない——どちらが正しいかを
決められるのは文脈を読める読み手だけだから（misheard と同じ方針）。
"""
from __future__ import annotations
import re

# 添える目印。ひらがなと長音だけを括弧と「?」で囲む。普通の文に出る括弧書きと区別するため形を固定する
_HINT = re.compile(r"\(([ぁ-ゖー]+)\?\)")


def hint(sound: str) -> str:
    """音のかなを目印の形にする"""
    return f"({sound}?)"


def strip_hints(text: str) -> str:
    """目印を外す。翻訳など、元の文字起こしだけが要るところに渡す前に使う"""
    return _HINT.sub("", text)
